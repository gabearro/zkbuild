#!/usr/bin/env python3
"""Embed the toolchain's own headers into the guest image (part of toolchain_root)."""
import os, sys
out = sys.argv[1]
entries = []
def add(root, prefix):
    for dp, _, fns in os.walk(root):
        for fn in sorted(fns):
            p = os.path.join(dp, fn)
            rel = os.path.relpath(p, root).replace(os.sep, '/')
            entries.append((prefix + rel, open(p, 'rb').read()))
add('libc/include', '/usr/include/')
add('zkcc/chibicc/include', './include/')
entries.sort()
with open(out, 'w') as f:
    f.write('/* generated by gen-sysroot.py: toolchain headers baked into the image */\n#include "zk.h"\n')
    for i, (name, data) in enumerate(entries):
        f.write('static const u8 d%d[] = {%s};\n' % (i, ','.join(str(b) for b in data) or '0'))
    f.write('const struct zk_sysfile { const char *name; const u8 *data; u32 len; } zk_sysroot[] = {\n')
    for i, (name, data) in enumerate(entries):
        f.write('  {"%s", d%d, %d},\n' % (name, i, len(data)))
    f.write('};\nconst u32 zk_sysroot_n = %d;\n' % len(entries))
print('sysroot: %d files' % len(entries))
